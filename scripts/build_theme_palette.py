"""Build CSS color tokens for both UI themes; never transform artwork or canvases.

Existing editor selectors, native CSS variables and layout stay intact. Each
literal UI color receives a named token and a fallback; the opposite theme uses
an explicit palette. Re-running this script is safe after editing CSS colors.
"""
import colorsys
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    'portal': ('dark', ['portal/static/style.css']),
    'knowledge': ('light', ['knowledge/static/style.css']),
    'animation': ('light', ['animation/static/style.css']),
    'media': ('light', ['media/static/style.css']),
    'narrative': ('dark', [p.relative_to(ROOT).as_posix() for p in (ROOT / 'narrative/src').glob('*.css')]),
    'effects': ('dark', ['effects/vendor/css/editor.css', 'effects/frontend/integration.css']),
}
COLOR = re.compile(r'#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{4}\b|#[0-9a-fA-F]{3}\b')
DECLARATION = re.compile(r'([\w-]+)\s*:\s*([^;{}]+)(?=;|})')
EXISTING = re.compile(r'var\(--fantasy-color-[\w-]+,\s*(#[0-9a-fA-F]{3,8})\)')


def opposite(value, base):
    raw = value[1:]
    if len(raw) in (3, 4): raw = ''.join(c * 2 for c in raw)
    alpha = raw[6:]
    rgb = [int(raw[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    hue, light, saturation = colorsys.rgb_to_hls(*rgb)
    if base == 'light':
        stops = [(0.20, .90), (.35, .80), (.48, .72), (.62, .65), (.72, .53),
                 (.82, .37), (.90, .27), (.94, .19), (.98, .14), (1.01, .11)]
    else:
        stops = [(.07, .94), (.12, .98), (.18, .96), (.23, .91), (.30, .80),
                 (.38, .66), (.52, .42), (.68, .32), (.82, .24), (1.01, .13)]
    target = next(result for maximum, result in stops if light < maximum)
    # Low-chroma surfaces share one neutral hue. Keep meaningful accent/status hues.
    if saturation < .23 or (base == 'light' and light > .94) or (base == 'dark' and light < .13):
        hue, saturation = .59, .17
    elif (base == 'light' and light > .8) or (base == 'dark' and light < .25):
        saturation = min(saturation, .25)
    else:
        saturation = min(saturation, .66)
    channels = colorsys.hls_to_rgb(hue, target, saturation)
    return '#' + ''.join(f'{round(c * 255):02x}' for c in channels) + alpha


def main():
    output = ['/* Generated by scripts/build_theme_palette.py. UI color tokens only. */']
    for module, (base, files) in SOURCES.items():
        palette = {}
        originals = {}
        for filename in files:
            path = ROOT / filename
            source = EXISTING.sub(r'\1', path.read_text(encoding='utf-8'))
            def declaration(match):
                prop, value = match.groups()
                if prop in {'box-shadow', 'text-shadow', 'filter', 'mask-image', 'content'} or 'url(' in value:
                    return match.group(0)
                if prop != 'font-family':
                    value = re.sub(r'(?<![\w-])white(?![\w-])', '#ffffff', value, flags=re.I)
                    value = re.sub(r'(?<![\w-])black(?![\w-])', '#000000', value, flags=re.I)
                def color(found):
                    original = found.group(0).lower()
                    token = '--fantasy-color-' + module + '-' + original[1:]
                    palette[token] = opposite(original, base)
                    originals[token] = original
                    return f'var({token},{original})'
                return prop + ':' + COLOR.sub(color, value)
            changed = DECLARATION.sub(declaration, source)
            path.write_text(changed, encoding='utf-8', newline='\n')
        alternative = 'light' if base == 'dark' else 'dark'
        output.append(f'html[data-fantasy-module="{module}"][data-theme="{alternative}"]' + '{')
        output += [f'  {token}:{value};' for token, value in sorted(palette.items())]
        output.append('}')
        if module in {'animation', 'media'}:
            # These light editors already have a dark navigation rail. Keep that
            # native rail dark in night mode instead of reversing it into white.
            selector = 'body>aside' if module == 'animation' else '.sidebar'
            output.append(f'html[data-fantasy-module="{module}"][data-theme="dark"] {selector}' + '{')
            output += [f'  {token}:{value};' for token, value in sorted(originals.items())]
            output.append('}')
    (ROOT / 'portal/static/theme-palette.css').write_text('\n'.join(output) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
